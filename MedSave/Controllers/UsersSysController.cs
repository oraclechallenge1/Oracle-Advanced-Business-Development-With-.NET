using MedSave.DTOs.UsersSys;
using MedSave.Services.UsersSys;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace MedSave.Controllers;

[ApiController]
[Authorize]
[Route("api/[controller]")]
public class UsersSysController : ControllerBase
{
    private readonly IUsersSysService _usersSysService;

    public UsersSysController(IUsersSysService usersSysService)
    {
        _usersSysService = usersSysService;
    }

    /// <summary>
    /// Returns all registered Users.
    /// </summary>
    /// <remarks>
    /// Non-paginated endpoint. Returns the complete collection of Users, without contact.
    ///
    /// Possible status codes:
    /// - 200 OK: collection returned successfully
    /// - 500 Internal Server Error: unexpected error while retrieving data
    /// </remarks>
    /// <returns></returns>
    [HttpGet]
    [ProducesResponseType(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status500InternalServerError)]
    public async Task<IActionResult> GetAll()
    {
        try
        {
            var dtos = await _usersSysService.GetAllAsync();

            return Ok(new { items = dtos });
        }
        catch (Exception e)
        {
            return StatusCode(500, new
            {
                message = "Internal error when searching for the Users",
                details = e.Message
            });
        }
    }

    /// <summary>
    /// Gets a specific User by ID.
    /// </summary>
    /// <param name="id">User ID.</param>
    /// <remarks>
    /// Endpoint that returns a specific User with details about its contact.
    ///
    /// Possible status codes:
    ///
    /// - 200 OK: User found and returned in the response body
    /// - 404 Not Found: no User with the provided ID was found
    /// - 500 Internal Server Error: unexpected server error
    /// </remarks>
    /// <returns>Resource <see cref="UsersSysDTO"/></returns>
    [HttpGet("{id:long}")]
    [ProducesResponseType(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status500InternalServerError)]
    public async Task<IActionResult> GetById(long id)
    {
        try
        {
            var dto = await _usersSysService.GetByIdAsync(id);

            return Ok(dto);
        }
        catch (UsersSysService.NotFoundException ex)
        {
            return StatusCode(404, ex.Message);
        }
        catch (Exception ex)
        {
            return StatusCode(500, new
            {
                message = "Internal error when searching for the user",
                details = ex.Message
            });
        }
    }

